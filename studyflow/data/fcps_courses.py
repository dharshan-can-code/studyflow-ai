# ============================================================
# LOOKUPS
# ============================================================

def _flatten(*catalogs):
    courses = {}
    for catalog in catalogs:
        for subject, names in catalog.items():
            for name in names:
                courses.setdefault(name, subject)
    return courses


def for_grade(grade):
    if grade in MIDDLE_GRADES:
        return _flatten(MIDDLE_SCHOOL)
    if grade in HIGH_GRADES:
        return _flatten(HIGH_SCHOOL)
    return _flatten(HIGH_SCHOOL, MIDDLE_SCHOOL)


def level_for_grade(grade):
    if grade in MIDDLE_GRADES:
        return "middle school"
    if grade in HIGH_GRADES:
        return "high school"
    return ""
